import type { SVGProps } from 'react';
import {
  ArrowLeft,
  ArrowRight,
  Check,
  ChartColumn,
  ChartPie,
  ChevronDown,
  ChevronUp,
  Clock,
  Copy,
  Download,
  ExternalLink,
  EyeOff,
  GitBranch,
  Globe,
  GripVertical,
  Info,
  List,
  SlidersHorizontal,
  Link,
  Lock,
  Maximize,
  Merge,
  Minimize,
  Minus,
  Monitor,
  Ellipsis,
  Pause,
  Pencil,
  Play,
  Plus,
  Repeat,
  Scan,
  Send,
  Settings,
  Square,
  Trash2,
  TrendingUp,
  TriangleAlert,
  Undo2,
  Users,
  X,
  LayoutGrid,
  type LucideIcon,
} from 'lucide-react';

const ICONS = {
  pen: Pencil,
  grid: LayoutGrid,
  drag: GripVertical,
  x: X,
  plus: Plus,
  minus: Minus,
  up: ChevronUp,
  down: ChevronDown,
  info: Info,
  repeat: Repeat,
  lock: Lock,
  send: Send,
  link: Link,
  monitor: Monitor,
  clock: Clock,
  users: Users,
  pause: Pause,
  play: Play,
  stop: Square,
  settings: Settings,
  download: Download,
  fit: Scan,
  fullscreen: Maximize,
  exitfullscreen: Minimize,
  check: Check,
  copy: Copy,
  warning: TriangleAlert,
  chart: ChartColumn,
  branch: GitBranch,
  trending: TrendingUp,
  pie: ChartPie,
  trash: Trash2,
  merge: Merge,
  eyeoff: EyeOff,
  undo: Undo2,
  globe: Globe,
  external: ExternalLink,
  more: Ellipsis,
  list: List,
  filter: SlidersHorizontal,
  back: ArrowLeft,
  next: ArrowRight,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 20, ...rest }: { name: IconName; size?: number } & Omit<SVGProps<SVGSVGElement>, 'ref'>) {
  const C = ICONS[name];
  return <C size={size} strokeWidth={2.25} aria-hidden="true" focusable="false" {...rest} />;
}
